def _deny_rules(policy):
    globs = []
    for h in policy["hard_rules"]:
        if h["kind"] == "permission_deny":
            for d in h["deny"]:
                m = re.fullmatch(r"Bash\((.*)\)", d)
                if m and m.group(1) not in globs:
                    globs.append(m.group(1))
    flags = {}
    for p in policy["providers"]:
        if p.get("binary") and p["forbidden_flags"]:
            flags.setdefault(p["binary"], [])
            flags[p["binary"]] += [f for f in p["forbidden_flags"] if f not in flags[p["binary"]]]
    return {"deny_globs": globs, "bypass_prefixes": list(BYPASS_PREFIXES), "bypass_substrings": list(BYPASS_SUBSTRINGS),
            "provider_forbidden_flags": flags}


