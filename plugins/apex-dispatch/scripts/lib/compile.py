#!/usr/bin/env python3
"""apex-dispatch policy compiler (python3 stdlib only).

Loads resources/dispatch.default.json, optionally merges a per-repo overlay,
validates the result against resources/schema.json plus the referential and
governance checks below, and renders the committed artifacts:

  resources/compiled/policy.json   merged default policy, sorted keys
  resources/compiled/VERSION       plugin version + sha256 of the inputs
  agents/<role>[-<effort>].md      one per enabled role (+ effort variants)
  resources/settings-snippet.json  layer A deny rules + layer I sandbox
  hooks/hooks.json                 only hook scripts present under hooks/

Artifacts are built from the default policy only; an overlay is applied at
runtime by readers (see --print-merged). An overlay may configure policy
within the hard rules but never weaken confinement or change what a hard rule
refers to (see overlay_checks). agents/ is fully generated: --check flags any
agents/*.md that is not an expected artifact, and comparisons are byte-exact.

Usage: compile.py <plugin-root> [--check | --write | --print-merged] [--overlay PATH]
       compile.py <plugin-root> --target codex [--out DIR] [--check | --write]
  no flag        regenerate (write) the artifacts
  --overlay PATH alone validates the overlay and checks the artifacts like
                 --check (it never rewrites the plugin); add --write to also
                 regenerate the artifacts
  --target codex the codex-side mirror of the same default policy (spec §5.1):
                 AGENTS.md (roles, their contracts and the governance rules),
                 config.toml (profiles apex-dispatch-build / -readonly with the
                 policy's sandbox and approval settings), hooks.json (a
                 PreToolUse deny hook) and apex-dispatch-deny.py (the hook: the
                 layer-A deny patterns and each provider's forbidden flags).
                 Written to --out DIR (default resources/compiled/codex/, which
                 is committed); --check compares DIR byte-exactly. Install by
                 copying the files into $CODEX_HOME or passing --out there. The
                 default (Claude) target and its --check are unchanged by it.
Exit: 0 ok, 1 invalid policy/overlay or stale artifacts, 2 usage.
"""
