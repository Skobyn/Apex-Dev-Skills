def find_overlay():
    env = os.environ.get("APEX_DISPATCH_POLICY")
    if env:
        return env
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None
    p = os.path.join(top, ".claude", "apex-dispatch", "policy.json")
    return p if os.path.isfile(p) else None


def load_inputs(plugin_root):
    res = os.path.join(plugin_root, "resources")
    return {
        "default": load_json(os.path.join(res, "dispatch.default.json"), "default policy"),
        "sections": load_json(os.path.join(res, "sections.json"), "sections registry"),
        "schema": load_json(os.path.join(res, "schema.json"), "schema"),
    }


def merged_with_overlay(inputs, overlay_path):
    """The default policy merged with the overlay at overlay_path, disabled
    entries subtracted, validated with the schema, governance and overlay
    bounds (overlay_checks). Raises PolicyError naming every problem."""
    overlay = load_json(overlay_path, "overlay")
    secs = inputs["sections"]["sections"]
    try:
        merged = apply_disabled(merge_policy(inputs["default"], overlay, secs, overlay_path), secs, inputs["schema"])
        default_policy = apply_disabled(merge_policy(inputs["default"], {}, secs), secs, inputs["schema"])
        validate_policy(merged, inputs["schema"], "merged policy (overlay %s)" % overlay_path,
                        extra=lambda m: overlay_checks(default_policy, m))
    except (TypeError, KeyError, AttributeError) as e:
        # A value of the wrong shape (a list or object where an id, tag or flag
        # string belongs) that the named checks did not catch first: still a
        # named refusal, never a traceback.
        raise PolicyError(["overlay %s: a value has the wrong type for its field (%s: %s); ids, tags, classes, "
                           "roles and flags are strings" % (overlay_path, type(e).__name__, e)])
    return merged


def runtime_policy(plugin_root, overlay_path=None):
    """What runtime readers (route.sh, hooks) use: the committed
    resources/compiled/policy.json, or, when this repo has an overlay
    (overlay_path, else find_overlay()), the default merged with it through
    the same merge as --print-merged. Raises PolicyError."""
    if overlay_path is None:
        overlay_path = find_overlay()
    if overlay_path is None:
        return load_json(os.path.join(plugin_root, "resources", "compiled", "policy.json"), "compiled policy")
    return merged_with_overlay(load_inputs(plugin_root), overlay_path)


def main(argv):
    if not argv:
        print("usage: compile.py <plugin-root> [--check | --write | --print-merged] [--overlay PATH]", file=sys.stderr)
        return 2
    root, args = os.path.abspath(argv[0]), argv[1:]
    check = printing = write = False
    overlay_path = target = out_dir = None
    i = 0
    while i < len(args):
        a = args[i]
        if a in ("--target", "--out"):
            if i + 1 >= len(args):
                print("compile: %s needs a value" % a, file=sys.stderr)
                return 2
            if a == "--target":
                target = args[i + 1]
            else:
                out_dir = os.path.abspath(args[i + 1])
            i += 2
            continue
        if a == "--check":
            check = True
        elif a == "--print-merged":
            printing = True
        elif a == "--write":
            write = True
        elif a == "--overlay":
            if i + 1 >= len(args):
                print("compile: --overlay needs a path", file=sys.stderr)
                return 2
            overlay_path = args[i + 1]
            i += 1
        elif a in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            print("compile: unknown argument %s" % a, file=sys.stderr)
            return 2
        i += 1
    if sum((check, printing, write)) > 1:
        print("compile: --check, --write and --print-merged are exclusive", file=sys.stderr)
        return 2
    if target not in (None, "claude", "codex"):
        print("compile: --target must be codex (or claude, the default)", file=sys.stderr)
        return 2
    if out_dir is not None and target != "codex":
        print("compile: --out is only for --target codex", file=sys.stderr)
        return 2
    if target == "codex":
        if printing or overlay_path is not None:
            print("compile: --target codex takes only --out, --check and --write", file=sys.stderr)
            return 2
        try:
            return codex_target(root, load_inputs(root), out_dir, check)
        except PolicyError as e:
            for line in e.errors:
                print("compile: " + line, file=sys.stderr)
            return 1
    if overlay_path is not None and not (printing or write):
        check = True          # validating an overlay never rewrites the plugin unless --write says so
    try:
        inputs = load_inputs(root)
        artifacts = build(root, inputs)
        if overlay_path is None and printing:
            overlay_path = find_overlay()
        merged = None
        if overlay_path is not None:
            merged = merged_with_overlay(inputs, overlay_path)
    except PolicyError as e:
        for line in e.errors:
            print("compile: " + line, file=sys.stderr)
        return 1
    if printing:
        sys.stdout.write(dumps(merged if merged is not None else json.loads(artifacts["resources/compiled/policy.json"])))
        return 0
    expected = set(artifacts)
    on_disk = agents_on_disk(root)
    orphans = [a for a, marked in on_disk if marked and a not in expected]
    foreign = [a for a, marked in on_disk if not marked and a not in expected]
    if check:
        problems = []
        for rel in sorted(artifacts):
            p = os.path.join(root, rel)
            if not os.path.isfile(p):
                problems.append("missing: " + rel)
                continue
            if read_text(p) != artifacts[rel]:
                problems.append("stale: " + rel)
        problems += ["orphaned: " + a for a in orphans]
        problems += ["not generated: %s (agents/ is fully generated; remove it)" % a for a in foreign]
        for line in problems:
            print("compile --check: " + line, file=sys.stderr)
        if problems:
            print("compile --check: %d artifact(s) out of date; run scripts/compile.sh" % len(problems), file=sys.stderr)
            return 1
        print("compile --check: %d artifacts up to date%s" % (len(artifacts), "; overlay valid" if merged is not None else ""))
        return 0
    written = 0
    for rel, text in sorted(artifacts.items()):
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        cur = read_text(p) if os.path.isfile(p) else None
        if cur != text:
            with open(p, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            written += 1
            print("compile: wrote " + rel)
    for a in orphans:
        os.remove(os.path.join(root, a))
        print("compile: removed " + a)
    print("compile: %d artifacts, %d written, %d removed%s" % (len(artifacts), written, len(orphans), "; overlay valid" if merged is not None else ""))
    for a in foreign:
        print("compile: %s is not a generated artifact; agents/ is fully generated, remove it" % a, file=sys.stderr)
    return 1 if foreign else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
