def _is_id_list(lst):
    return all(isinstance(x, dict) and isinstance(x.get("id"), str) for x in lst)


def deep_merge(base, over):
    """Project wins. Objects deep-merge; [] clears; lists of {id} objects merge
    by id (entries merged field by field); other lists and scalars replace."""
    if isinstance(base, dict) and isinstance(over, dict):
        out = copy.deepcopy(base)
        for k, v in over.items():
            out[k] = deep_merge(base[k], v) if k in base else copy.deepcopy(v)
        return out
    if isinstance(base, list) and isinstance(over, list):
        if not over:
            return []
        if base and _is_id_list(base) and _is_id_list(over):
            return merge_by_id(base, over)
        return copy.deepcopy(over)
    return copy.deepcopy(over)


def merge_by_id(base, over):
    out = [copy.deepcopy(b) for b in base]
    index = {e["id"]: i for i, e in enumerate(out)}
    for o in over:
        if o["id"] in index:
            out[index[o["id"]]] = deep_merge(out[index[o["id"]]], o)
        else:
            index[o["id"]] = len(out)
            out.append(copy.deepcopy(o))
    return out


def check_overlay_shape(overlay, sections, src):
    errs = []
    if not isinstance(overlay, dict):
        return ["overlay %s: top level must be a JSON object" % src]
    by_name = {s["name"]: s for s in sections}
    for key, val in overlay.items():
        if key == "$comment":
            continue
        sec = by_name.get(key)
        if sec is None:
            errs.append("overlay %s: unknown section '%s' (known: %s)" % (src, key, ", ".join(sorted(by_name))))
            continue
        if sec["kind"] == "map":
            if not isinstance(val, dict):
                errs.append("overlay %s: section '%s' must be an object" % (src, key))
            continue
        if not isinstance(val, list):
            errs.append("overlay %s: section '%s' must be a list" % (src, key))
            continue
        for i, e in enumerate(val):
            if not isinstance(e, dict) or not isinstance(e.get("id"), str) or not e["id"]:
                errs.append("overlay %s: %s[%d] must be an object with a non-empty string id" % (src, key, i))
            elif sec["merge"] == "subtract":
                if "section" in e and not isinstance(e["section"], str):
                    errs.append("overlay %s: disabled entry '%s': section must be a string" % (src, e["id"]))
                r = e.get("reason")
                if not isinstance(r, str) or not r.strip():
                    errs.append("overlay %s: disabled entry '%s' has no reason (a reason is required)" % (src, e["id"]))
    return errs


def merge_policy(default, overlay, sections, src="overlay"):
    errs = check_overlay_shape(overlay, sections, src)
    if not errs and overlay:
        errs = overlay_allowlist(default, overlay, src)
    if errs:
        raise PolicyError(errs)
    merged = copy.deepcopy(default)
    for sec in sections:
        name = sec["name"]
        if name not in overlay:
            continue
        over = overlay[name]
        rule = sec["merge"]
        if rule == "deep":
            merged[name] = deep_merge(merged.get(name, {}), over)
        elif rule == "by-id":
            merged[name] = [] if over == [] else merge_by_id(merged.get(name, []), over)
            if name == "providers" and over:
                union_forbidden(default.get(name, []), over, merged[name])
        elif rule == "add-only":
            if over == []:
                errs.append("overlay %s: %s cannot be cleared (hard rules outrank the overlay)" % (src, name))
                continue
            known = {e["id"] for e in merged.get(name, [])}
            for e in over:
                if e["id"] in known:
                    errs.append("overlay %s: %s '%s' already exists and cannot be replaced; add a rule with a new id" % (src, name, e["id"]))
            merged[name] = merged.get(name, []) + copy.deepcopy([e for e in over if e["id"] not in known])
        elif rule == "subtract":
            if over == []:
                merged[name] = []
            else:
                cur = merged.get(name, [])
                keyed = {(e.get("section"), e["id"]): i for i, e in enumerate(cur)}
                for e in over:
                    k = (e.get("section"), e["id"])
                    if k in keyed:
                        cur[keyed[k]] = copy.deepcopy(e)
                    else:
                        keyed[k] = len(cur)
                        cur.append(copy.deepcopy(e))
                merged[name] = cur
        else:
            errs.append("sections.json: unknown merge rule '%s' for %s" % (rule, name))
    if errs:
        raise PolicyError(errs)
    return merged


# Provider fields an overlay may set on a default provider (an allowlist: any
# other field is refused). New provider ids come only from the default policy.
PROVIDER_OVERLAY_FIELDS = {"id", "enabled", "allowed_classes", "roles_allowed", "max_tier", "min_acceptance", "forbidden_flags",
                           "model", "verified_versions"}


def overlay_allowlist(default, overlay, src):
    """Positive checks on the raw overlay. Providers: only enabled, narrowing
    allowed_classes/roles_allowed, lowering max_tier, raising min_acceptance
    and adding forbidden_flags; no new ids; never cleared. Tiers: not
    overlayable at all (no change, no new tier, no disabling)."""
    errs = []
    if "tiers" in overlay:
        errs.append("overlay %s: tiers cannot be changed, added or cleared by an overlay (tiers are the referents of the hard floors; they come only from the default policy)" % src)
    for d in overlay.get("disabled", []):
        if d.get("section") == "tiers" or (d.get("section") is None and any(t["id"] == d.get("id") for t in default["tiers"])):
            errs.append("overlay %s: disabled entry '%s': tiers cannot be disabled by an overlay" % (src, d.get("id")))
    if "providers" not in overlay:
        return errs
    if overlay["providers"] == []:
        return errs + ["overlay %s: providers cannot be cleared by an overlay (disable a provider with enabled: false)" % src]
    dp = {e["id"]: e for e in default["providers"]}
    trank = {t["id"]: t["rank"] for t in default["tiers"]}
    for o in overlay["providers"]:
        pid = o["id"]
        where = "overlay %s: providers[%s]" % (src, pid)
        d = dp.get(pid)
        if d is None:
            errs.append("%s: an overlay may not add a provider (new providers come only from the plugin's default policy)" % where)
            continue
        for k in sorted(set(o) - PROVIDER_OVERLAY_FIELDS):
            errs.append("%s.%s: an overlay may not set this field (allowed: %s)" % (where, k, ", ".join(sorted(PROVIDER_OVERLAY_FIELDS - {"id"}))))
        if "enabled" in o and not isinstance(o["enabled"], bool):
            errs.append("%s.enabled: must be true or false" % where)
        for k in ("allowed_classes", "roles_allowed"):
            if k in o:
                if not isinstance(o[k], list) or not all(isinstance(x, str) for x in o[k]):
                    errs.append("%s.%s: must be a list of strings" % (where, k))
                elif not set(o[k]) <= set(d[k]):
                    errs.append("%s.%s: an overlay may only narrow it to a subset of the default %s" % (where, k, json.dumps(d[k])))
        if "max_tier" in o and not isinstance(o["max_tier"], str):
            errs.append("%s.max_tier: must be a tier id string" % where)
        elif "max_tier" in o and trank.get(o["max_tier"], 1 << 30) > trank[d["max_tier"]]:
            errs.append("%s.max_tier: an overlay may only lower it (default %s)" % (where, json.dumps(d["max_tier"])))
        if "min_acceptance" in o:
            v = o["min_acceptance"]
            if not isinstance(v, (int, float)) or isinstance(v, bool) or v < d["min_acceptance"]:
                errs.append("%s.min_acceptance: an overlay may only raise it (default %s)" % (where, d["min_acceptance"]))
        if "forbidden_flags" in o:
            if not isinstance(o["forbidden_flags"], list) or (o["forbidden_flags"] == [] and d["forbidden_flags"]):
                errs.append("%s.forbidden_flags: add-only; an overlay may add forbidden flags, never clear or remove them" % where)
        if "model" in o and o["model"] is not None and (not isinstance(o["model"], str) or o["model"].startswith("-")):
            errs.append("%s.model: must be a model id string (not a flag)" % where)
        if "model" in o and d["kind"] != "subprocess":
            errs.append("%s.model: only a subprocess provider's model can be set" % where)
        if "verified_versions" in o and (not isinstance(o["verified_versions"], list)
                                         or not all(isinstance(x, str) for x in o["verified_versions"])):
            errs.append("%s.verified_versions: must be a list of version strings" % where)
    return errs


def union_forbidden(base, over, merged):
    """forbidden_flags of a provider is the default's list plus the overlay's."""
    dflt = {e["id"]: e for e in base}
    out = {e["id"]: e for e in merged}
    for o in over:
        if o["id"] in dflt and isinstance(o.get("forbidden_flags"), list):
            df = dflt[o["id"]]["forbidden_flags"]
            out[o["id"]]["forbidden_flags"] = list(df) + [f for f in o["forbidden_flags"] if f not in df]


def prune_refs(value, spec, defs, removed):
    """Drop list items that reference a disabled entry (schema-driven). A
    scalar reference to a disabled entry is left for validation to reject."""
    spec = resolve(spec, defs)
    if isinstance(value, list) and "items" in spec:
        item = resolve(spec["items"], defs)
        if "ref" in item:
            value[:] = [x for x in value if (item["ref"], x) not in removed]
        else:
            for x in value:
                prune_refs(x, item, defs, removed)
    elif isinstance(value, dict):
        for k, s in list(spec.get("required", {}).items()) + list(spec.get("optional", {}).items()):
            if k in value:
                prune_refs(value[k], s, defs, removed)


def apply_disabled(policy, sections, schema):
    errs = []
    removed = set()
    targets = [s["name"] for s in sections if s["merge"] == "by-id"]
    for d in policy.get("disabled", []):
        if not isinstance(d, dict):
            continue
        did, sec = d.get("id"), d.get("section")
        if not isinstance(d.get("reason"), str) or not d["reason"].strip():
            errs.append("disabled entry '%s' has no reason (a reason is required)" % did)
            continue
        if sec is not None:
            if sec not in targets:
                hint = " (hard rules cannot be disabled)" if sec == "hard_rules" else ""
                errs.append("disabled entry '%s': section '%s' is not a by-id section%s" % (did, sec, hint))
                continue
            hits = [sec] if any(e.get("id") == did for e in policy.get(sec, [])) else []
        else:
            hits = [s for s in targets if any(e.get("id") == did for e in policy.get(s, []))]
            if any(e.get("id") == did for e in policy.get("hard_rules", [])) and not hits:
                errs.append("disabled entry '%s' names a hard rule; hard rules cannot be disabled" % did)
                continue
        if not hits:
            errs.append("disabled entry '%s' matches no entry%s" % (did, " in " + sec if sec else ""))
        elif len(hits) > 1:
            errs.append("disabled entry '%s' is ambiguous (in %s); add \"section\"" % (did, ", ".join(hits)))
        else:
            policy[hits[0]] = [e for e in policy[hits[0]] if e.get("id") != did]
            removed.add((hits[0], did))
    if errs:
        raise PolicyError(errs)
    if removed:
        prune_refs(policy, schema["root"], schema["defs"], removed)
    return policy


# ------------------------------------------------------------ validation ----

TYPE_CHECKS = {
    "string": lambda v: isinstance(v, str),
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "number": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
    "null": lambda v: v is None,
    "array": lambda v: isinstance(v, list),
    "object": lambda v: isinstance(v, dict),
}


def resolve(spec, defs):
    if "$def" in spec:
        base = dict(resolve(defs[spec["$def"]], defs))
        base.update({k: v for k, v in spec.items() if k != "$def"})
        return base
    return spec


def validate(value, spec, path, defs, errs, refs):
    spec = resolve(spec, defs)
    types = spec.get("type")
    types = [types] if isinstance(types, str) else (types or [])
    if types and not any(TYPE_CHECKS[t](value) for t in types):
        errs.append("%s: expected %s, got %s" % (path, "|".join(types), json.dumps(value)[:60]))
        return
    if "const" in spec and value != spec["const"]:
        errs.append("%s: must be %s" % (path, json.dumps(spec["const"])))
    if "enum" in spec and value not in spec["enum"]:
        errs.append("%s: %s is not one of %s" % (path, json.dumps(value), ", ".join(json.dumps(x) for x in spec["enum"])))
    if isinstance(value, str):
        if "min" in spec and len(value) < spec["min"]:
            errs.append("%s: must not be empty" % path)
        if "pattern" in spec and not re.fullmatch(spec["pattern"], value):
            errs.append("%s: %s does not match /%s/" % (path, json.dumps(value), spec["pattern"]))
        if "ref" in spec:
            refs.append((path, spec["ref"], value))
    elif isinstance(value, (int, float)) and not isinstance(value, bool):
        if "min" in spec and value < spec["min"]:
            errs.append("%s: %s is below %s" % (path, value, spec["min"]))
        if "max" in spec and value > spec["max"]:
            errs.append("%s: %s is above %s" % (path, value, spec["max"]))
    elif isinstance(value, list):
        if len(value) < spec.get("min_items", 0):
            errs.append("%s: needs at least %d item(s)" % (path, spec["min_items"]))
        if spec.get("unique"):
            seen = set()
            for x in value:
                k = json.dumps(x, sort_keys=True)
                if k in seen:
                    errs.append("%s: duplicate item %s" % (path, k))
                seen.add(k)
        if spec.get("unique_ids"):
            seen = set()
            for x in value:
                if isinstance(x, dict) and "id" in x:
                    if x["id"] in seen:
                        errs.append("%s: duplicate id %s" % (path, json.dumps(x["id"])))
                    seen.add(x["id"])
        if "items" in spec:
            for i, x in enumerate(value):
                label = x["id"] if isinstance(x, dict) and isinstance(x.get("id"), str) else i
                validate(x, spec["items"], "%s[%s]" % (path, label), defs, errs, refs)
    elif isinstance(value, dict) and ("required" in spec or "optional" in spec):
        req, opt = spec.get("required", {}), spec.get("optional", {})
        for k, s in req.items():
            if k not in value:
                errs.append("%s: missing required key '%s'" % (path, k))
            else:
                validate(value[k], s, "%s.%s" % (path, k), defs, errs, refs)
        for k, s in opt.items():
            if k in value:
                validate(value[k], s, "%s.%s" % (path, k), defs, errs, refs)
        if not spec.get("additional", False):
            for k in value:
                if k not in req and k not in opt:
                    errs.append("%s: unknown key '%s'" % (path, k))


def governance_checks(p):
    """Checks the schema language cannot express."""
    errs = []
    tiers = {t["id"]: t for t in p["tiers"]}
    ranks = [t["rank"] for t in p["tiers"]]
    if len(set(ranks)) != len(ranks):
        errs.append("tiers: ranks must be unique")
    for c in p["classes"]:
        f, ce = tiers.get(c["tier_floor"]), tiers.get(c["tier_ceiling"])
        if f and ce and f["rank"] > ce["rank"]:
            errs.append("classes[%s]: tier_floor %s is above tier_ceiling %s" % (c["id"], c["tier_floor"], c["tier_ceiling"]))
        if c["fanout"]["shape"] == "single" and c["fanout"]["max_lanes"] != 1:
            errs.append("classes[%s]: fanout single must have max_lanes 1" % c["id"])
    for r in p["roles"]:
        where = "roles[%s]" % r["id"]
        tools, dis = set(r["tools"]), set(r["disallowed_tools"])
        if r["id"] in RESERVED_AGENT_NAMES:
            errs.append("%s: name collides with an apex-scope-loop agent" % where)
        for t in r["tools"]:
            if "(" in t or "*" in t:
                errs.append("%s: tools entry %s is a pattern; tools must name whole tools (a Bash pattern grants all of Bash)" % (where, json.dumps(t)))
        if "Agent" in tools or "Task" in tools:
            errs.append("%s: no generated agent may hold Agent/Task (spawn depth 1)" % where)
        if "Agent" not in dis:
            errs.append("%s: disallowed_tools must include Agent" % where)
        if tools & dis:
            errs.append("%s: tools and disallowed_tools overlap: %s" % (where, ", ".join(sorted(tools & dis))))
        if r["read_only"] and tools & EDIT_TOOLS:
            errs.append("%s: read_only role holds edit tools %s" % (where, ", ".join(sorted(tools & EDIT_TOOLS))))
        if r["read_only"] and not EDIT_TOOLS <= dis:
            errs.append("%s: read_only role must disallow %s" % (where, ", ".join(sorted(EDIT_TOOLS))))
        if r["id"] in REVIEWER_ROLES:
            if sorted(tools) != ["Glob", "Grep", "Read"]:
                errs.append("%s: reviewer tools must be exactly Read, Grep, Glob" % where)
            if not set(REVIEWER_DISALLOWED) <= dis:
                errs.append("%s: reviewer disallowed_tools must include %s" % (where, ", ".join(REVIEWER_DISALLOWED)))
        for v in r["effort_variants"]:
            if EFFORT_ORDER.index(v) <= EFFORT_ORDER.index(r["effort"]):
                errs.append("%s: effort variant %s must be above the base effort %s" % (where, v, r["effort"]))
    for h in p["hard_rules"]:
        where = "hard_rules[%s]" % h["id"]
        need = {"route_floor": ("when", "then", "match"), "permission_deny": ("deny",), "sandbox": ("sandbox",)}[h["kind"]]
        for k in need:
            if k not in h:
                errs.append("%s: kind %s needs '%s'" % (where, h["kind"], k))
        for k in ("when", "then", "match", "deny", "sandbox"):
            if k in h and k not in need:
                errs.append("%s: kind %s does not take '%s'" % (where, h["kind"], k))
        for rule in h.get("deny", []):
            if rule.lower().startswith("ask"):
                errs.append("%s: ask rules are forbidden" % where)
    if not any(h["kind"] == "permission_deny" for h in p["hard_rules"]):
        errs.append("hard_rules: at least one permission_deny rule is required (layer A)")
    if sum(1 for h in p["hard_rules"] if h["kind"] == "sandbox") != 1:
        errs.append("hard_rules: exactly one sandbox rule is required (layer I)")
    rungs = sorted(p["escalation"]["rungs"], key=lambda r: r["at_failures"])
    if len({r["at_failures"] for r in rungs}) != len(rungs):
        errs.append("escalation.rungs: at_failures must be unique")
    if rungs and rungs[-1]["action"] != "halt":
        errs.append("escalation.rungs: the last rung must halt")
    if rungs and rungs[0]["action"] != "effort_up":
        errs.append("escalation.rungs: the first rung must raise effort before model")
    if p["escalation"]["max_review_rounds"] > MAX_REVIEW_ROUNDS:
        errs.append("escalation.max_review_rounds: %d is above %d (three review rounds max)" % (p["escalation"]["max_review_rounds"], MAX_REVIEW_ROUNDS))
    if rungs and rungs[-1]["at_failures"] > MAX_HALT_FAILURES:
        errs.append("escalation.rungs: the halt rung at_failures %d is above %d (failures=3 halts)" % (rungs[-1]["at_failures"], MAX_HALT_FAILURES))
    # Tier ranks are monotonic with model strength and effort.
    by_rank = sorted(p["tiers"], key=lambda t: t["rank"])
    for lo, hi in zip(by_rank, by_rank[1:]):
        if MODEL_STRENGTH[lo["model"]] > MODEL_STRENGTH[hi["model"]]:
            errs.append("tiers: tier %s (rank %d, %s) is above tier %s (rank %d, %s) but uses a weaker model; rank must be monotonic with model strength" % (hi["id"], hi["rank"], hi["model"], lo["id"], lo["rank"], lo["model"]))
        if EFFORT_ORDER.index(lo["effort"]) > EFFORT_ORDER.index(hi["effort"]):
            errs.append("tiers: tier %s (rank %d, effort %s) is above tier %s (rank %d, effort %s) but uses a lower effort; rank must be monotonic with effort" % (hi["id"], hi["rank"], hi["effort"], lo["id"], lo["rank"], lo["effort"]))
    # Provider confinement: no forced flag may bypass layer A or a forbidden flag.
    for pr in p["providers"]:
        where = "providers[%s]" % pr["id"]
        forbidden = set(pr["forbidden_flags"])
        for f in pr["forced_flags"]:
            if f.startswith(BYPASS_PREFIXES) or any(x in f for x in BYPASS_SUBSTRINGS):
                errs.append("%s: forced flag %s matches a layer-A bypass pattern" % (where, json.dumps(f)))
            elif f in forbidden or f.split("=", 1)[0] in forbidden:
                errs.append("%s: forced flag %s is in forbidden_flags" % (where, json.dumps(f)))
        if pr["sandbox_mode"] is not None and any(x in pr["sandbox_mode"] for x in BYPASS_SUBSTRINGS):
            errs.append("%s: sandbox_mode %s disables provider confinement" % (where, json.dumps(pr["sandbox_mode"])))
    # Roles a hard rule's review shape needs cannot be disabled.
    enabled = {r["id"] for r in p["roles"] if r["enabled"]}
    for h in p["hard_rules"]:
        shape = h.get("then", {}).get("review_shape")
        for role in SHAPE_ROLES.get(shape, []):
            if role not in enabled:
                errs.append("roles[%s]: required by hard rule %s (review_shape %s) and cannot be disabled" % (role, h["id"], shape))
    return errs


def _rank(order, v):
    return order.index(v) if v in order else -1


def _when_overlaps(a, b):
    """True when two route_floor `when` objects share a condition (equal value,
    or intersecting tags_any); identical conditions always overlap."""
    if a == b:
        return True
    for k in set(a) & set(b):
        if k == "tags_any":
            if set(a[k]) & set(b[k]):
                return True
        elif a[k] == b[k]:
            return True
    return False


def _weaker_then(new, old, tiers):
    """Names of `then` keys where `new` is weaker than `old` (route_floor rules
    combine by max, so an appended rule may only match or tighten)."""
    rank = {t["id"]: t["rank"] for t in tiers}
    weak = []
    for k in set(new) & set(old):
        n, o = new[k], old[k]
        if k == "review_shape":
            bad = _rank(SHAPE_ORDER, n) < _rank(SHAPE_ORDER, o)
        elif k == "review_diversity":
            bad = _rank(DIVERSITY_ORDER, n) < _rank(DIVERSITY_ORDER, o)
        elif k == "fanout":
            bad = _rank(FANOUT_ORDER, n) < _rank(FANOUT_ORDER, o)
        elif k == "tier_floor":
            bad = rank.get(n, -1) < rank.get(o, -1)
        elif k == "tier_ceiling":
            bad = rank.get(n, 1 << 30) > rank.get(o, 1 << 30)
        elif k == "tier_floor_rungs_above_last":
            bad = n < o
        elif k == "classes_only":
            bad = not set(n) <= set(o)
        else:  # class, reviewer_family, external_builders, human_gate: must match
            bad = n != o
        if bad:
            weak.append(k)
    return sorted(weak)


def overlay_checks(default, merged):
    """An overlay may configure policy within the hard rules but never weaken
    confinement or change what a hard rule refers to. `default` is the
    validated default policy; `merged` the validated overlay-merged policy."""
    errs = []
    dmap = lambda sec: {e["id"]: e for e in default[sec]}
    # Tiers: the referents of the hard floors (strong = opus/high, ...).
    dt = dmap("tiers")
    for t in merged["tiers"]:
        d = dt.get(t["id"])
        for k in ("model", "effort", "rank") if d else ():
            if t[k] != d[k]:
                errs.append("tiers[%s].%s: an overlay may not change %s (default %s); a hard rule refers to it" % (t["id"], k, json.dumps(t[k]), json.dumps(d[k])))
    # Providers: identity and confinement.
    dp = dmap("providers")
    for pr in merged["providers"]:
        d = dp.get(pr["id"])
        if not d:
            continue
        where = "providers[%s]" % pr["id"]
        for k in ("kind", "family", "binary"):
            if pr[k] != d[k]:
                errs.append("%s.%s: an overlay may not change %s (default %s)" % (where, k, json.dumps(pr[k]), json.dumps(d[k])))
        missing = [f for f in d["forbidden_flags"] if f not in pr["forbidden_flags"]]
        if missing:
            errs.append("%s.forbidden_flags: an overlay may not remove %s (add-only)" % (where, ", ".join(missing)))
        if pr["forced_flags"][:len(d["forced_flags"])] != d["forced_flags"]:
            errs.append("%s.forced_flags: an overlay may not remove or replace the default forced flags (append only)" % where)
        if pr["sandbox_mode"] != d["sandbox_mode"]:
            old, new = d["sandbox_mode"], pr["sandbox_mode"]
            if old is None or new is None or old not in SANDBOX_LOOSENESS or new not in SANDBOX_LOOSENESS \
                    or SANDBOX_LOOSENESS[new] > SANDBOX_LOOSENESS[old]:
                errs.append("%s.sandbox_mode: an overlay may not loosen or remove the sandbox mode (%s -> %s; order read-only|strict < workspace-write < danger-full-access)" % (where, json.dumps(old), json.dumps(new)))
    # Roles: read-only stays read-only; tools only shrink; disallowed only grow.
    dr = dmap("roles")
    for r in merged["roles"]:
        d = dr.get(r["id"])
        if not d:
            continue
        where = "roles[%s]" % r["id"]
        if d["read_only"] and not r["read_only"]:
            errs.append("%s.read_only: an overlay may not make a read-only role writable" % where)
        added = [t for t in r["tools"] if t not in d["tools"]]
        if added:
            errs.append("%s.tools: an overlay may not grant %s (tools may only be removed)" % (where, ", ".join(added)))
        dropped = [t for t in d["disallowed_tools"] if t not in r["disallowed_tools"]]
        if dropped:
            errs.append("%s.disallowed_tools: an overlay may not remove %s (add-only)" % (where, ", ".join(dropped)))
    # Appended route_floor rules may not be weaker than a default rule they overlap.
    dh = [h for h in default["hard_rules"] if h["kind"] == "route_floor"]
    known = {h["id"] for h in default["hard_rules"]}
    for h in merged["hard_rules"]:
        if h["id"] in known or h["kind"] != "route_floor":
            continue
        if "tier_ceiling" in h["then"]:
            errs.append("hard_rules[%s].then.tier_ceiling: an overlay-appended rule may not set a tier ceiling (it could undercut a default rule's tier floor)" % h["id"])
        for d in dh:
            if _when_overlaps(h["when"], d["when"]):
                weak = _weaker_then(h["then"], d["then"], merged["tiers"])
                if weak:
                    errs.append("hard_rules[%s]: weaker than hard rule %s on an overlapping condition (%s); matching hard rules combine by max, so an added rule may only match or tighten" % (h["id"], d["id"], ", ".join(weak)))
    # Escalation: stricter, never looser.
    me, de = merged["escalation"], default["escalation"]
    if me["max_review_rounds"] > de["max_review_rounds"]:
        errs.append("escalation.max_review_rounds: an overlay may lower it, not raise it above %d" % de["max_review_rounds"])
    halt = lambda e: max((r["at_failures"] for r in e["rungs"] if r["action"] == "halt"), default=0)
    if halt(me) > halt(de):
        errs.append("escalation.rungs: an overlay may not move the halt rung above at_failures %d" % halt(de))
    return errs


def validate_policy(policy, schema, where, extra=None):
    """Schema, references, then governance (plus `extra`, e.g. overlay_checks)
    on a schema-valid policy; every problem is reported together."""
    errs, refs = [], []
    validate(policy, schema["root"], "policy", schema["defs"], errs, refs)
    if errs:
        raise PolicyError(["%s: %s" % (where, e) for e in errs])
    for path, section, value in refs:
        ids = {e.get("id") for e in policy.get(section, []) if isinstance(e, dict)}
        if value not in ids:
            errs.append("%s: unknown %s reference %s" % (path, section.rstrip("s") if section != "classes" else "class", json.dumps(value)))
    if not errs:
        errs += governance_checks(policy)
        errs += extra(policy) if extra else []
    if errs:
        raise PolicyError(["%s: %s" % (where, e) for e in errs])


